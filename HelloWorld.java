/*
 * Problem: Print "Hello, World!" and your name to the console.
 * This is the traditional first program in any language. It shows the
 * basic structure of a Java program: a class, and a main method where
 * execution starts.
 *
 * Example Input:
 * (no input required)
 *
 * Example Output:
 * Hello, World!
 * My name is Shahriar Kabir.
 */
public class HelloWorld {
    public static void main(String[] args) {
        System.out.println("Hello, World!");
        System.out.println("My name is Shahriar Kabir.");
    }
}

